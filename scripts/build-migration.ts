/* eslint-disable no-console */
/**
 * Builds a Prisma migration folder WITHOUT a database connection:
 *   1. `prisma migrate diff --from-migrations … --to-schema-datamodel` (or
 *      --from-empty for the baseline) produces the DDL delta.
 *   2. Every prisma/sql/*.sql file listed in `extraSql` is appended verbatim
 *      (triggers, partial indexes, CHECK constraints Prisma cannot express).
 *
 * Usage: npx ts-node scripts/build-migration.ts <name> [--baseline] [--sql 0001_phase2_constraints.sql,...]
 * Then:  npx prisma migrate deploy   (or `migrate dev` on a dev DB)
 */
import { execSync } from 'child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'fs';
import { join } from 'path';

const args = process.argv.slice(2);
const name = args.find((a) => !a.startsWith('--'));
if (!name) { console.error('usage: build-migration <name> [--baseline] [--sql a.sql,b.sql]'); process.exit(1); }
const baseline = args.includes('--baseline');
const sqlArg = args[args.indexOf('--sql') + 1];
const extraSql = args.includes('--sql') && sqlArg ? sqlArg.split(',') : [];

const root = join(__dirname, '..');
const migrationsDir = join(root, 'prisma', 'migrations');
if (!existsSync(migrationsDir)) mkdirSync(migrationsDir, { recursive: true });

const stamp = new Date().toISOString().replace(/[-:TZ.]/g, '').slice(0, 14);
const folder = join(migrationsDir, `${stamp}_${name}`);
if (existsSync(folder)) { console.error(`${folder} already exists`); process.exit(1); }

const from = baseline ? '--from-empty' : `--from-migrations ${JSON.stringify(migrationsDir)} --shadow-database-url ${JSON.stringify(process.env.SHADOW_DATABASE_URL ?? process.env.DIRECT_URL ?? '')}`;
const cmd = `npx prisma migrate diff ${from} --to-schema-datamodel prisma/schema --script`;
console.log(`> ${cmd}`);
let ddl = execSync(cmd, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });

const parts = [`-- Migration: ${name}\n-- Generated by scripts/build-migration.ts on ${new Date().toISOString()}\n`, ddl.trim(), ''];
for (const f of extraSql) {
  const p = join(root, 'prisma', 'sql', f);
  if (!existsSync(p)) { console.error(`missing ${p}`); process.exit(1); }
  parts.push(`\n-- ─── ${f} ───\n`, readFileSync(p, 'utf8').trim(), '');
}
mkdirSync(folder, { recursive: true });
writeFileSync(join(folder, 'migration.sql'), parts.join('\n'), 'utf8');
const lock = join(migrationsDir, 'migration_lock.toml');
if (!existsSync(lock)) writeFileSync(lock, '# Please do not edit this file manually\n# It should be added in your version-control system (i.e. Git)\nprovider = "postgresql"\n');
console.log(`wrote ${folder}\\migration.sql (${readdirSync(folder).length} file)`);
